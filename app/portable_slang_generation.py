"""Slang C++ generation shared by native CPU and browser WASM."""
import hashlib,json,os,platform,re,subprocess,tempfile
from pathlib import Path


from portable_file_identity import file_value, file_digest, stamp
from threading import RLock

_source_cache = {}
_source_lock = RLock()


def source_hashes(root,source):
    # Remember every lexical include edge as well as the resolved file. A
    # retargeted symlink must invalidate the graph even if its old target lives.
    root = Path(os.fspath(root))
    cache_key = (str(root.absolute()), str(source))
    with _source_lock:
        saved = _source_cache.get(cache_key)
        if saved is not None and all(stamp(p) == st for p, st in saved[0]):
            return dict(saved[1])
        requested_source = root/source
        visited = {requested_source: stamp(requested_source)}
        root = root.resolve()
        found = {}
        def visit(path):
            visited[path] = stamp(path)
            path = path.resolve()
            visited[path] = stamp(path)
            key = path.relative_to(root).as_posix()
            if key in found:return
            def read(p):
                raw = p.read_bytes()
                return hashlib.sha256(raw).hexdigest(), tuple(re.findall(rb'^\s*#include\s+"([^"]+)"', raw, re.M))
            digest, includes = file_value(path, 'slang-includes', read)
            found[key] = digest
            for include in includes:visit(path.parent/include.decode())
        visit(root/source)
        if any(stamp(p) != st for p, st in visited.items()):
            raise RuntimeError('Shared sources changed during build; discard generated outputs')
        _source_cache[cache_key] = (tuple(visited.items()), dict(found))
        return found

def validate_counter_snapshots(generated):
    """Reject known lossy lowering before either backend can execute it.

    This inspects generated bytes without changing them or their hashes.
    Mutation snapshots must not become reflexive ordered comparisons.
    """
    pattern=r'(?m)^\s*if\s*\(\s*\(\s*(?P<value>[A-Za-z_]\w*->(?:removalCount|carrierCount)_\d+)\s*\)\s*(?:>=|<=|>|<)\s*\(\s*(?P=value)\s*\)'
    if re.search(pattern,generated):
        raise ValueError('Generated counter snapshot became a reflexive comparison')




def build(root,source,entry,*,target=None):
    if target not in (None,"cpp"):raise ValueError("Unsupported generation target")
    return _build_cpp(root,source,entry)


def slang_compiler(root):
    compiler_root=Path(os.environ.get('NIKKE_SLANG_ROOT',root/f'.tools/slang-2026.20-{platform.system()}-{platform.machine()}')).resolve()
    return compiler_root/'bin'/('slangc.exe' if os.name=='nt' else 'slangc')


CPP_FLAGS=('-target','cpp','-fp-mode','precise','-line-directive-mode','none')


def cpp_compiler_identity(compiler):
    return dict(file_value(compiler, 'slang-identity', lambda p: dict(sha256=file_digest(p),
        version=subprocess.check_output([str(p),'-version'],stderr=subprocess.STDOUT,timeout=10).decode('utf-8','replace'))))


def _build_cpp(root,source,entry,*,native_binary64=False):
    flags=(*CPP_FLAGS, '-DPORTABLE_NATIVE_BINARY64=1') if native_binary64 else CPP_FLAGS
    hashes=source_hashes(root,source)
    compiler=slang_compiler(root)
    identity_data=dict(source_hashes=hashes,source=str(source),compiler=cpp_compiler_identity(compiler),entry=entry,flags=list(flags))
    identity=hashlib.sha256(json.dumps(identity_data,sort_keys=True,separators=(',',':')).encode()).hexdigest()
    directory=root/'research/portable-build/cpp'/identity;directory.mkdir(parents=True,exist_ok=True)
    output=directory/(Path(source).stem+'.cpp');receipt=directory/'build.json'
    # Serialize identical builds across fresh processes; publish files atomically.
    import fcntl
    with (directory/'build.lock').open('a') as lock:
        fcntl.flock(lock,fcntl.LOCK_EX)
        try:
            saved=json.loads(receipt.read_text())
            hit=output.stat().st_size>0 and saved==dict(identity=identity,**identity_data,cpp_sha256=file_digest(output))
        except (OSError,ValueError):hit=False
        if not hit:
            process=subprocess.run([str(compiler),str(root/source),'-entry',entry,*flags],capture_output=True,timeout=90)
            if process.returncode:raise RuntimeError(process.stderr.decode('utf-8','replace'))
            raw=process.stdout
            if not raw:raise RuntimeError('Empty Slang C++ output')
        if hit:
            file_value(output, 'counter-snapshots', lambda p: validate_counter_snapshots(p.read_text(encoding='utf-8')))
        else:
            validate_counter_snapshots(raw.decode('utf-8'))
        if hashes!=source_hashes(root,source):raise RuntimeError('Shared sources changed during build; discard generated outputs')
        if not hit:
            saved=dict(identity=identity,**identity_data,cpp_sha256=hashlib.sha256(raw).hexdigest())
            for destination,data in ((output,raw),(receipt,(json.dumps(saved,indent=2)+'\n').encode())):
                with tempfile.NamedTemporaryFile(dir=directory,delete=False) as temporary:
                    temporary.write(data);temporary_path=Path(temporary.name)
                temporary_path.replace(destination)
    return {'cpp':output},hashes
