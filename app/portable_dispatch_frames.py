"""Bit-preserving frame storage shared by the resident CUDA/Metal executor."""
import re
from pathlib import Path
CAPACITY=32
WORDS=32
STORAGE_WORDS=CAPACITY*WORDS
# Gaps preserve the full-feature Frame's 64-bit alignment. Optional fields do
# not change offsets; padding words are zeroed on every whole-frame store.
FIELDS=(('attackGroup',0,'uint','PORTABLE_ATTACK_GROUPS'),
        ('notifyDealt',2,'uint64_t','PORTABLE_PARENT_FIXED_DAMAGE'),
        ('hitCrit',4,'uint',None),('skillCritRate',6,'uint64_t',None),
        ('interruptAmount',8,'uint64_t',None),('interruptReach',10,'uint',None),
        *((name,11+i,'uint',None) for i,name in enumerate(('mode','event','owner','cursor','target','repeatRow','repeatLeft','repeatPassive'))),
        ('argument',19,'int',None),
        *((name,20+i*2,'uint64_t',None) for i,name in enumerate(('value','time','healthValue','healthPrevious','healthNext','gaugeFlat'))))

def check_frame_type(root):
    text=(Path(root)/'gpu/dispatch_frame_type.slang').read_text()
    body=text.split('struct Frame\n{',1)[1].split('};',1)[0]
    body=re.sub(r'^#.*$', '', body,flags=re.M)
    actual=[]
    for typ,names in re.findall(r'\b(uint64_t|uint|int)\s+([^;]+);',body):
        actual.extend((name.strip(),typ) for name in names.split(','))
    if actual!=[(name,typ) for name,_,typ,_ in FIELDS]:raise ValueError('Dispatch Frame fields changed; review codec and storage capacity')
    return dict(capacity=CAPACITY,frame_words=WORDS,storage_words=STORAGE_WORDS)

def schema():
    lines=['// Generated by portable_dispatch_frames.py; no event or numeric logic.',
           '#ifdef PORTABLE_RESIDENT_FRAME_STACK',
           '#if !defined(PORTABLE_RESIDENT_RUNTIME) || !defined(PORTABLE_COMPOSED_ARENA)',
           '#error Resource frames require the resident composed executor.', '#endif',
           'struct DispatchFrameRef','{','    uint caseIndex,index;']
    for name,offset,typ,guard in FIELDS:
        if guard:lines.append('#ifdef '+guard)
        word=f'runtimeStates[caseIndex].dispatchFrameWords[index*32+{offset}]'
        value=(f'uint64_t({word})|(uint64_t(runtimeStates[caseIndex].dispatchFrameWords[index*32+{offset+1}])<<32)' if typ=='uint64_t' else 'asint('+word+')' if typ=='int' else word)
        lines += [f'    property {typ} {name}', '    {', '        [ForceInline] get', '        {',
                  '            if(index>=32){runtimeStates[caseIndex].error=1;return 0;}',
                  f'            return {value};','        }',f'        [ForceInline] set({typ} value)','        {',
                  '            if(index>=32){runtimeStates[caseIndex].error=1;return;}']
        low='value' if typ=='uint' else 'asuint(value)' if typ=='int' else 'uint(value)'
        lines.append(f'            {word}={low};')
        if typ=='uint64_t':lines.append(f'            runtimeStates[caseIndex].dispatchFrameWords[index*32+{offset+1}]=uint(value>>32);')
        lines+=['        }','    }']
        if guard:lines.append('#endif')
    lines+=['};','struct DispatchFrameStack','{','    uint caseIndex;',
            '    __subscript(uint index) -> DispatchFrameRef','    {',
            '        [ForceInline] get { DispatchFrameRef f;f.caseIndex=caseIndex;f.index=index;return f; }',
            '        [ForceInline] set(DispatchFrameRef value)',
            '        { if(value.caseIndex!=caseIndex || value.index!=index)runtimeStates[caseIndex].error=64; }',
            '    }','};','[ForceInline]',
            'Frame loadDispatchFrame(DispatchFrameStack frames,uint index)','{',
            '    Frame f={};']
    for name,_,_,guard in FIELDS:
        if guard:lines.append('#ifdef '+guard)
        lines.append(f'    f.{name}=frames[index].{name};')
        if guard:lines.append('#endif')
    lines+=['    return f;','}','[ForceInline]',
            'void storeDispatchFrame(inout DispatchFrameStack frames,uint index,Frame f)','{',
            '    if(index>=32){runtimeStates[frames.caseIndex].error=1;return;}',
            '    runtimeStates[frames.caseIndex].dispatchFrameWords[index*32+1]=0;',
            '    runtimeStates[frames.caseIndex].dispatchFrameWords[index*32+5]=0;']
    for name,_,_,guard in FIELDS:
        if guard:lines.append('#ifdef '+guard)
        lines.append(f'    frames[index].{name}=f.{name};')
        if guard:lines.append('#endif')
    lines+=['}',
            '#define DISPATCH_FRAMES(name) DispatchFrameStack name',
            '#define DISPATCH_FRAMES_INIT(name,s) name.caseIndex=s.resourceOutput/P_OUTPUT_WORDS;',
            '#define DISPATCH_FRAME_LOAD(frames,index) loadDispatchFrame(frames,index)',
            '#define DISPATCH_FRAME_STORE(frames,index,value) storeDispatchFrame(frames,index,value)',
            '#else','#define DISPATCH_FRAMES(name) Frame name[32]',
            '#define DISPATCH_FRAMES_INIT(name,s)',
            '#define DISPATCH_FRAME_LOAD(frames,index) frames[index]',
            '#define DISPATCH_FRAME_STORE(frames,index,value) frames[index] = value', '#endif','']
    return '\n'.join(lines)

def encode(values):
    if set(values)-{r[0] for r in FIELDS}:raise ValueError('Unknown frame field')
    words=[0]*WORDS
    for name,offset,typ,_ in FIELDS:
        value=values.get(name,0);bits=64 if typ=='uint64_t' else 32
        low=-(1<<31) if typ=='int' else 0;high=(1<<31)-1 if typ=='int' else (1<<bits)-1
        if type(value) is not int or not low<=value<=high:raise ValueError('Frame scalar outside exact wire range: '+name)
        words[offset]=value&0xffffffff
        if bits==64:words[offset+1]=value>>32
    return words

def decode(words):
    if len(words)!=WORDS or any(type(x) is not int or not 0<=x<=0xffffffff for x in words):raise ValueError('Invalid full frame words')
    result={}
    for name,offset,typ,_ in FIELDS:
        value=words[offset]
        if typ=='uint64_t':value|=words[offset+1]<<32
        elif typ=='int' and value>=1<<31:value-=1<<32
        result[name]=value
    return result
