import importlib.util
from pathlib import Path
import sys
import tempfile
import unittest
ROOT=Path(__file__).resolve().parents[1]
sys.path[:0]=[str(ROOT/p) for p in ('app','research','scripts')]
from portable_compiler_stats import cuda_statistics
spec=importlib.util.spec_from_file_location('compiler_stats_cli',ROOT/'scripts/nikke_gpu.py')
cli=importlib.util.module_from_spec(spec);spec.loader.exec_module(cli)


class CompilerStatisticsTests(unittest.TestCase):
    def test_call_graph_is_lexical_bounded_and_stops_at_noinline(self):
        raw=b'''void leaf() {}
void __noinline__ boundary() { leaf(); }
void middle() { boundary(); leaf(); }
void root() { middle(); middle(); /* leaf(); */ const char* s="leaf()"; }
'''
        graph=cuda_statistics(raw,caller='root')['call_graph']
        edges={(e['caller'],e['callee']):e for e in graph['edges']}
        self.assertEqual(edges[('root','middle')]['calls'],2)
        self.assertNotIn(('root','leaf'),edges);self.assertNotIn(('boundary','leaf'),edges)
        self.assertTrue(edges[('middle','boundary')]['noinline'])
        for name in ('absent',''):
            with self.assertRaises(ValueError):cuda_statistics(raw,caller=name)
        with self.assertRaises(ValueError):cuda_statistics(raw+b'void root(int x) {}',caller='root')

    def test_spans_ignore_comment_string_braces_and_forward_declarations(self):
        source=b'''void forward(int x);
static __device__ __noinline__ void largest(int x) {
 // } if (ignored) {
 const char* text="} if (also_ignored) {";
 if(x) { for(int i=0;i<2;i++) { x++; } }
}
extern "C" __global__ void entry() { largest(1); }
'''
        result=cuda_statistics(source)
        self.assertEqual(result['functions'],2);self.assertEqual(result['noinline_functions'],1)
        large,entry=result['largest_functions']
        self.assertEqual(large['name'],'largest');self.assertEqual(large['line'],2)
        self.assertEqual(large['branches'],2);self.assertTrue(entry['global_entry'])
        for top in (0,51,True):
            with self.assertRaises(ValueError):cuda_statistics(source,top=top)
        with self.assertRaises(ValueError):cuda_statistics(b'void bad() {')

    def test_saved_manifest_and_evidence_are_checked_without_promoting_execution(self):
        with tempfile.TemporaryDirectory() as f:
            root=Path(f);source=root/'generated.cu';source.write_bytes(b'void example() {}')
            cli.write(root/'evidence.json',dict(generated_sha256={'cuda':cli.sha(source.read_bytes())}))
            # Normal export receipts intentionally omit raw/generated sources;
            # the retained evidence anchors their exact generated bytes.
            cli.write(root/'artifacts.json',dict(files=cli.file_records(root,['evidence.json'])))
            output=root/'stats.json';result=cli.compiler_statistics(root,output)
            self.assertTrue(result['source_integrity_verified']);self.assertFalse(result['calculation_verified'])
            self.assertFalse(result['compiler_verified']);self.assertEqual(result['nvrtc_compile_calls'],0)
            with self.assertRaisesRegex(ValueError,'already exists'):cli.compiler_statistics(root,output)
            source.write_bytes(b'changed')
            with self.assertRaises(ValueError):cli.compiler_statistics(root,root/'bad.json')
            self.assertFalse((root/'bad.json').exists())


if __name__=='__main__':unittest.main()
