class MetalWorkDeadlineTests(unittest.TestCase):
    """CPU-only adapter receipts and fail-closed behavior; no Swift invocation."""
    def test_budget_scales_by_cases_and_has_a_hard_cap(self):
        from portable_backend import metal_gpu_timeout_seconds as budget
        self.assertEqual([budget(n) for n in (1,2,8,9,65536)],[600,1200,4800,4800,4800])
        for bad in (0,-1,True,1.5,'2'):
            with self.subTest(bad=bad),self.assertRaises(ValueError):budget(bad)

    def harness(self,counts,*,sequence=False,timeout=False):
        import json,struct
        from types import SimpleNamespace
        from unittest.mock import Mock,patch
        import portable_backend as backend
        with tempfile.TemporaryDirectory() as folder:
            root=Path(folder);(root/'research/portable-build').mkdir(parents=True)
            artifact=root/'shader';artifact.write_bytes(b'unchanged generated bytes')
            batches=[struct.pack('<'+'I'*(n+1),n,*range(n)) for n in counts]
            hashes={'source':'sealed'}
            def command(argv,**kwargs):
                if timeout:raise RuntimeError('Metal timeout (gpu phase): mocked hung device')
                paths=json.loads(Path(argv[3]).read_text()) if sequence else [dict(input=argv[3],output=argv[4])]
                rows=[]
                for path,n in zip(paths,counts):
                    Path(path['output']).write_bytes(b'\0'*(n*4))
                    rows.append(dict(cases=n,command_status='completed',gpu_seconds=0))
                return SimpleNamespace(returncode=0,stdout=json.dumps(dict(batches=rows) if sequence else rows[0]),stderr='')
            mock=Mock(side_effect=command)
            with patch.multiple(backend,ROOT=root,build=Mock(return_value=({'metal':artifact},hashes)),resident_plan=Mock(return_value=None),source_hashes=Mock(return_value=hashes),run_metal_command=mock),patch.object(backend.platform,'system',return_value='Darwin'):
                call=lambda:backend.execute_batches('source','entry',batches,1,1) if sequence else backend.execute('source','entry',batches[0],1,1)
                if timeout:
                    with self.assertRaisesRegex(RuntimeError,'Metal timeout .*gpu phase'):call()
                    result=None
                else:result=call()
            self.assertEqual(mock.call_count,1)  # Scaling does not introduce retries/splits.
            return result,mock.call_args.kwargs

    def test_single_case_receipt_records_calibrated_default(self):
        import hashlib
        result,kwargs=self.harness([1]);raw,evidence=result
        self.assertEqual(kwargs,{})
        self.assertEqual(raw,b'\0'*4)
        self.assertEqual(evidence,dict(transport=dict(cases=1,command_status='completed',gpu_seconds=0,compile_timeout_seconds=300,gpu_timeout_seconds=600),source_sha256={'source':'sealed'},generated_sha256={'metal':hashlib.sha256(b'unchanged generated bytes').hexdigest()},input_sha256=hashlib.sha256(b'\1\0\0\0\0\0\0\0').hexdigest(),output_sha256=hashlib.sha256(raw).hexdigest(),gpu_execution_verified=True,backend='metal'))

    def test_packed_dispatch_records_actual_command_deadlines(self):
        result,kwargs=self.harness([8])
        self.assertEqual(kwargs,dict(compile_timeout=300,gpu_timeout=4800))
        self.assertEqual(result[1]['transport']['gpu_timeout_seconds'],kwargs['gpu_timeout'])
        self.assertEqual(result[1]['transport']['compile_timeout_seconds'],kwargs['compile_timeout'])

    def test_sequence_budget_counts_all_cases_and_records_shared_deadline(self):
        result,kwargs=self.harness([2,1,2],sequence=True)
        self.assertEqual(kwargs,dict(compile_timeout=300,gpu_timeout=3000))
        for index,(_,evidence) in enumerate(result):
            t=evidence['transport']
            self.assertEqual((t['gpu_timeout_seconds'],t['compile_timeout_seconds']),(3000,300))
            self.assertEqual((t['session_dispatches'],t['session_dispatch_index']),(3,index))

    def test_mock_timeout_never_retries_splits_or_publishes_partial_success(self):
        for counts,sequence in (([8],False),([2,1,2],True),([1],False)):
            with self.subTest(counts=counts,sequence=sequence):
                result,kwargs=self.harness(counts,sequence=sequence,timeout=True)
                self.assertIsNone(result)
                self.assertEqual(kwargs.get('gpu_timeout',600),min(4800,600*sum(counts)))


class MetalDeadlineSourceHistoryTests(unittest.TestCase):
    def test_exact_inverse_preserves_old_bytes_and_rejects_additional_edits(self):
        import hashlib,json
        from portable_metal_deadline_source_contract import historical_backend_bytes
        root=Path(__file__).resolve().parents[1]
        current=(root/'app/portable_backend.py').read_bytes()
        before=historical_backend_bytes(root,current)
        row=json.loads((root/'tests/fixtures/portable-metal-work-deadline-source-delta.json').read_text())
        self.assertEqual(hashlib.sha256(before).hexdigest(),row['before_sha256'])
        self.assertEqual(historical_backend_bytes(root,before),before)
        for changed in (current+b'\n',current.replace(b'METAL_GPU_TIMEOUT_MAX_SECONDS=4800',b'METAL_GPU_TIMEOUT_MAX_SECONDS=4801'),current.replace(b'process.kill()',b'process.wait()')):
            with self.assertRaisesRegex(ValueError,'Unreviewed'):historical_backend_bytes(root,changed)
        with tempfile.TemporaryDirectory() as folder:
            path=Path(folder)/'tests/fixtures';path.mkdir(parents=True)
            (path/'portable-metal-work-deadline-source-delta.json').write_text('{}')
            with self.assertRaisesRegex(ValueError,'ledger changed'):historical_backend_bytes(folder,current)

    def test_calibrated_inverse_checks_its_own_ledger_and_reconstructs_v1(self):
        import hashlib,json
        from portable_metal_deadline_source_contract import historical_backend_bytes
        root=Path(__file__).resolve().parents[1]
        current=(root/'app/portable_backend.py').read_bytes()
        from portable_native_backend_source_contract import reviewed_bytes
        current=reviewed_bytes(root,'app/portable_backend.py',current)
        name='portable-metal-calibrated-deadline-source-delta.json'
        row=json.loads((root/'tests/fixtures'/name).read_text())
        self.assertEqual(hashlib.sha256(current).hexdigest(),row['after_sha256'])
        self.assertEqual(row['before_sha256'],'1c5586206da404682c045dfe9cd89faa33530cf47b5b99207a8d2b7607421de2')
        with tempfile.TemporaryDirectory() as folder:
            path=Path(folder)/'tests/fixtures';path.mkdir(parents=True)
            old='portable-metal-work-deadline-source-delta.json'
            (path/old).write_bytes((root/'tests/fixtures'/old).read_bytes())
            (path/name).write_text('{}')
            with self.assertRaisesRegex(ValueError,'Calibrated Metal deadline ledger changed'):historical_backend_bytes(folder,current)
