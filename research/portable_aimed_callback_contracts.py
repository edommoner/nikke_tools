def verify(case,native):
    sets=native['physical_packet_sets']
    actual=dict(damage=native['damage'],hp=[x['hp'] for x in native['allies']],shots=native['shots'],
        physical_shots=len(sets),returned_packets=sum(len(x['packets']) for x in sets),private_receipts=len(native['interrupt_landings']),
        packets_sha256=digest(sets),counter_sha256=digest(native['target_counters']),named_sha256=digest(native['named_state']),accounting=native['parts_skill_accounting'])
    assert actual==CONTRACTS[case['name']],('native aimed callback contract',case['name'],actual,CONTRACTS[case['name']])
    completions=native['target_counters']['completions']
    assert len(completions)==1 and completions[0]['time']==sets[0]['time'] and completions[0]['reason']=='threshold'
    owner=[s for s in sets if s['owner']==0]
    first=owner[0]['packets'];assert len(first)%2==0
    # The whole shot is sampled before body/part completion mutates ATK.
    assert all(p['damage']==first[i%2]['damage'] for i,p in enumerate(first))
    if case['name'].endswith('atk_pct'):
        assert owner[1]['packets'][0]['damage']==2*first[0]['damage'],'ATK child applies to following shot only'
    return dict(verified=True,reference_model_gap=False,physical_shots=len(sets),returned_packets=actual['returned_packets'],private_receipts=actual['private_receipts'],counter_completions=1,gpu_supported=False)
