def verify(case,native):
    landings=native['interrupt_landings'];names=roster_names(case)
    actual=dict(name=case['name'],damage=native['damage'],shots=native['shots'],
                hp=[a['hp'] for a in native['allies']],count=len(landings),
                owners=sorted(set(r['attacker'] for r in landings)),
                interrupt_damage=[sum(r['damage'] for r in landings if r['attacker']==n) for n in names],
                generations=sorted(set(r['target']['generation'] for r in landings)),
                dead_landings=sum(not r['before']['alive'] for r in landings),
                landing_sha256=hashlib.sha256(json.dumps(landings,sort_keys=True,separators=(',',':'),ensure_ascii=False).encode()).hexdigest())
    assert actual==CONTRACTS[case['name']],('private physical interrupt contract',actual,CONTRACTS[case['name']])
    for row in landings:
        before,after=row['before'],row['after']
        assert row['target']==before['handle']==after['handle'] and row['target']['kind']==6,'private identity/generation'
        assert row['canonical_credit']==0,'interrupt must not acquire canonical credit'
        assert row['accounted_after']==row['accounted_before']+row['damage'],'native external accounting'
        assert after['hits']==before['hits']+int(before['alive']),'dead same-frame target lifecycle'
        amount=row['damage'] if before['alive'] else 0
        assert after['dealt']==before['dealt']+amount and after['landed']==before['landed']+amount,'native target quantity'
    return dict(verified=True,reference_model_gap=False,private_receipts=len(landings),
                physical_interrupt_native_consumer=True,canonical_credit=0,gpu_supported=False)
