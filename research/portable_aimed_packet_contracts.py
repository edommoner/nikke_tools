def verify(case,native):
    sets=native['physical_packet_sets'];receipts=native['interrupt_landings']
    actual=dict(name=case['name'],damage=native['damage'],shots=native['shots'],hp=[a['hp'] for a in native['allies']],
                physical_shots=len(sets),physical_pellets=sum(s['pellets']*s['muzzles'] for s in sets),
                returned_packets=sum(len(s['packets']) for s in sets),interrupt_landings=len(receipts),
                interrupt_damage=[sum(r['damage'] for r in receipts if r['attacker']==n) for n in roster_names(case)],
                packets_sha256=hashlib.sha256(json.dumps(sets,sort_keys=True,separators=(',',':'),ensure_ascii=False).encode()).hexdigest())
    assert actual==CONTRACTS[case['name']],('actual physical packet set',actual,CONTRACTS[case['name']])
    assert [dict(owner=s['owner'],mode=s['mode'],time=s['time'],pellets=s['pellets'],muzzles=s['muzzles'],reach=max(p['reach'] for p in s['packets']),damage=s['packets'][0]['damage']) for s in sets]==native['projectile_shots'],'physical rather than returned packet count'
    return dict(verified=True,reference_model_gap=False,physical_shots=len(sets),returned_packets=actual['returned_packets'],
                private_receipts=len(receipts),gpu_supported=False)
